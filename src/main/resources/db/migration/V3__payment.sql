CREATE TABLE payment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         BIGINT        NOT NULL REFERENCES member (id),
    membership_type   VARCHAR(20)   NOT NULL,
    method            VARCHAR(20)   NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    amount            DECIMAL(10, 2) NOT NULL,
    discount_percent  INT           NOT NULL DEFAULT 0,
    card_last_four    VARCHAR(4),
    scheduled_date    DATE,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at       TIMESTAMP,
    CONSTRAINT ck_payment_membership_type
        CHECK (membership_type IN ('WEEKLY', 'BIWEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY')),
    CONSTRAINT ck_payment_method CHECK (method IN ('CARD', 'SPEI', 'CASH')),
    CONSTRAINT ck_payment_status CHECK (status IN ('APPROVED', 'PENDING'))
);
