CREATE TABLE push_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      BIGINT       NOT NULL REFERENCES member (id),
    token          VARCHAR(255) NOT NULL,
    registered_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_push_token_token UNIQUE (token)
);

CREATE INDEX ix_push_token_member_id ON push_token (member_id);

CREATE TABLE expiry_reminder (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT    NOT NULL REFERENCES member (id),
    due_date   DATE      NOT NULL,
    sent_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_expiry_reminder UNIQUE (member_id, due_date)
);

CREATE INDEX ix_expiry_reminder_due_date ON expiry_reminder (due_date);
