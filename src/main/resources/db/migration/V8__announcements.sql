CREATE TABLE announcement (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150)  NOT NULL,
    message     VARCHAR(2000) NOT NULL,
    type        VARCHAR(20)   NOT NULL,
    start_date  DATE          NOT NULL,
    end_date    DATE,
    created_by  BIGINT REFERENCES app_user (id),
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_announcement_type CHECK (type IN ('URGENT', 'MAINTENANCE', 'INFO', 'PROMOTION')),
    CONSTRAINT ck_announcement_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX ix_announcement_start_date ON announcement (start_date);

CREATE TABLE announcement_dismissal (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id  BIGINT      NOT NULL REFERENCES announcement (id) ON DELETE CASCADE,
    token_id         VARCHAR(36) NOT NULL,
    dismissed_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_announcement_dismissal UNIQUE (announcement_id, token_id)
);

CREATE INDEX ix_announcement_dismissal_token_id ON announcement_dismissal (token_id);
