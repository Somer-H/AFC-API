CREATE TABLE audit_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_user_id    BIGINT,
    actor_role       VARCHAR(20),
    action           VARCHAR(100)  NOT NULL,
    http_method      VARCHAR(10)   NOT NULL,
    path             VARCHAR(300)  NOT NULL,
    target_id        VARCHAR(50),
    outcome          VARCHAR(20)   NOT NULL,
    response_status  INT           NOT NULL,
    CONSTRAINT ck_audit_log_outcome CHECK (outcome IN ('SUCCESS', 'DENIED')),
    CONSTRAINT ck_audit_log_actor_role CHECK (actor_role IS NULL OR actor_role IN ('ADMIN', 'SOCIO'))
);

CREATE INDEX ix_audit_log_occurred_at ON audit_log (occurred_at);
CREATE INDEX ix_audit_log_actor_user_id ON audit_log (actor_user_id);
