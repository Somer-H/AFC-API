ALTER TABLE member ADD COLUMN user_id BIGINT REFERENCES app_user (id);
ALTER TABLE member ADD CONSTRAINT uq_member_user UNIQUE (user_id);

CREATE TABLE coach (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    avatar_url  VARCHAR(500),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE schedule_block (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week   VARCHAR(10) NOT NULL,
    start_time    TIME        NOT NULL,
    end_time      TIME        NOT NULL,
    max_capacity  INT         NOT NULL,
    coach_id      BIGINT REFERENCES coach (id),
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_schedule_block_day_of_week
        CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_schedule_block_max_capacity CHECK (max_capacity > 0),
    CONSTRAINT ck_schedule_block_times CHECK (start_time < end_time)
);

CREATE INDEX ix_schedule_block_day_of_week ON schedule_block (day_of_week);

CREATE TABLE booking (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_block_id  BIGINT      NOT NULL REFERENCES schedule_block (id),
    member_id          BIGINT      NOT NULL REFERENCES member (id),
    class_date         DATE        NOT NULL,
    status             VARCHAR(20) NOT NULL,
    created_at         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at       TIMESTAMP,
    CONSTRAINT ck_booking_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

CREATE INDEX ix_booking_schedule_block_class_date ON booking (schedule_block_id, class_date);
CREATE INDEX ix_booking_member_id ON booking (member_id);
