CREATE TABLE routine (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week  VARCHAR(10)   NOT NULL,
    title        VARCHAR(150)  NOT NULL,
    description  VARCHAR(1000),
    coach_id     BIGINT        NOT NULL REFERENCES coach (id),
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_routine_day_of_week UNIQUE (day_of_week),
    CONSTRAINT ck_routine_day_of_week
        CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE TABLE exercise (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id    BIGINT        NOT NULL REFERENCES routine (id),
    sort_order    INT           NOT NULL,
    name          VARCHAR(150)  NOT NULL,
    sets          INT           NOT NULL,
    reps          VARCHAR(30)   NOT NULL,
    rest_seconds  INT,
    video_url     VARCHAR(500),
    video_file    VARCHAR(60),
    CONSTRAINT ck_exercise_sets CHECK (sets > 0),
    CONSTRAINT ck_exercise_rest_seconds CHECK (rest_seconds IS NULL OR rest_seconds >= 0),
    CONSTRAINT ck_exercise_single_video CHECK (video_url IS NULL OR video_file IS NULL)
);

CREATE INDEX ix_exercise_routine_id ON exercise (routine_id);
