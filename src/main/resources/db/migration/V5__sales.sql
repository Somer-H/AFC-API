CREATE TABLE sale (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio           VARCHAR(20)    NOT NULL UNIQUE,
    total           DECIMAL(10, 2) NOT NULL,
    payment_method  VARCHAR(20)    NOT NULL,
    cashier_id      BIGINT REFERENCES app_user (id),
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sale_payment_method CHECK (payment_method IN ('CARD', 'SPEI', 'CASH'))
);

CREATE INDEX ix_sale_created_at ON sale (created_at);

CREATE TABLE sale_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       BIGINT         NOT NULL REFERENCES sale (id),
    product_id    BIGINT         NOT NULL REFERENCES product (id),
    product_name  VARCHAR(150)   NOT NULL,
    quantity      INT            NOT NULL,
    unit_price    DECIMAL(10, 2) NOT NULL,
    subtotal      DECIMAL(10, 2) NOT NULL,
    CONSTRAINT ck_sale_item_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_sale_item_sale_id ON sale_item (sale_id);
